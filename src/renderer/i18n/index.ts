export function translate(locale: Locale, key: string, values: Record<string, string | number> = {}): string {
  const value = dictionaries[locale][key] ?? dictionaries["pt-BR"][key] ?? key

  if (typeof value === "function") {
    return value(values)
  }

  return value
}
